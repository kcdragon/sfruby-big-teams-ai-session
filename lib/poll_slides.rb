require "cgi"
require "json"

# Writes one slide per question in deck/poll.json and puts them in the deck right
# after the GRAB YOUR PHONE slide. Generated slides are named poll-1.html, poll-2.html, ...
# and carry GENERATED_MARKER, so a rebuild can delete exactly the slides it made.
#
# Per question, poll.json can set:
#   "chart":   "columns" (fixed order, good for ranges), "bars" (ranked, top 8), or "cards"
#   "notes":   speaker notes
#   "heading": the slide title for "cards" (otherwise the prompt is the title)
#   "cards":   for "cards", one {"icon", "title", "text"} per option, in option order
module PollSlides
  GENERATED_MARKER = "<!-- Generated by bin/poll from deck/poll.json. Edit poll.json, not this file. -->"
  ANCHOR_SLIDE = "poll-vote"
  CHARTS = %w[columns bars cards].freeze

  module_function

  def build(definition:, slides_dir:, deck_path:)
    questions = definition.fetch("questions")
    questions.each_with_index { |question, index| validate!(question, index + 1) }

    removed = Dir[File.join(slides_dir, "*.html")].select { |path| File.read(path).include?(GENERATED_MARKER) }
    removed.each { |path| File.delete(path) }

    slide_ids = questions.each_with_index.map do |question, index|
      slide_id = "poll-#{index + 1}"
      File.write(File.join(slides_dir, "#{slide_id}.html"), slide_html(slide_id, question, index + 1, questions.size))
      slide_id
    end

    update_deck_order(deck_path, slide_ids, removed.map { |path| File.basename(path, ".html") })
    update_question_count(File.join(slides_dir, "#{ANCHOR_SLIDE}.html"), questions.size)
    slide_ids
  end

  def chart_for(question)
    question["chart"] || ((question["options"].size <= 6 && !question["allows_multiple"]) ? "columns" : "bars")
  end

  def validate!(question, number)
    chart = chart_for(question)
    raise ArgumentError, "Question #{number}: chart must be one of #{CHARTS.join(", ")}" unless CHARTS.include?(chart)
    return unless chart == "cards"

    cards = question.fetch("cards") { raise ArgumentError, "Question #{number}: a cards chart needs \"cards\"" }
    return if cards.size == question.fetch("options").size

    raise ArgumentError, "Question #{number}: #{question["options"].size} options but #{cards.size} cards"
  end

  def update_deck_order(deck_path, slide_ids, removed_ids)
    deck = JSON.parse(File.read(deck_path))
    order = deck.fetch("order") - removed_ids - slide_ids
    anchor_index = order.index(ANCHOR_SLIDE) or raise ArgumentError, "deck.json has no #{ANCHOR_SLIDE} slide to put the poll slides after"
    order.insert(anchor_index + 1, *slide_ids)
    deck["order"] = order
    File.write(deck_path, JSON.generate(deck))
  end

  def update_question_count(path, count)
    return unless File.exist?(path)

    html = File.read(path)
    noun = count == 1 ? "question" : "questions"
    File.write(path, html.sub(/Answer \d+ quick questions?/, "Answer #{count} quick #{noun}"))
  end

  def h(text) = CGI.escapeHTML(text.to_s)

  def slide_html(slide_id, question, number, total)
    chart = chart_for(question)
    body = chart == "cards" ? cards_html(question, number) : results_html(question, number, chart)
    <<~HTML
      #{GENERATED_MARKER}
      <section id="#{slide_id}" data-show-poll-badge data-transition="fade" style="background:linear-gradient(180deg, #3D78C2 0%, #79AEE3 100%);color:#14182E;font-family:'Deck Body', Arial, sans-serif;padding:128px 128px 160px;display:flex;flex-direction:column;gap:40px">
      <div style="position:absolute;left:0;right:0;bottom:0;height:88px;background:#8A93A6;border-top:24px solid #5DBB3A"></div>
      <div style="display:flex;justify-content:space-between;align-items:center;gap:32px">
      <p style="font-family:'Press Start 2P', monospace;font-size:24px;line-height:1.4;background:#F2C94C;color:#14182E;padding:16px 24px;border:4px solid #14182E;box-shadow:6px 6px 0 #14182E">LEVEL 1 · LIVE POLL · #{number} OF #{total}</p>
      <p data-poll="voters" style="font-family:'Press Start 2P', monospace;font-size:24px;line-height:1.4;background:#1B2C8F;color:#F2C94C;padding:16px 24px;border:4px solid #14182E;box-shadow:6px 6px 0 #14182E">0 PLAYERS HAVE VOTED</p>
      </div>
      #{body.chomp}
      <aside>#{h(question["notes"])}</aside>
      </section>
    HTML
  end

  # Ranked bars need the vertical room for 8 rows, and long prompts need it to fit on two lines.
  def heading_html(text, number, live_prompt:, chart:)
    size = (chart == "bars" || text.length > 60) ? 48 : 56
    poll_attributes = live_prompt ? %( data-poll="prompt" data-poll-question="#{number}") : ""
    %(<h2#{poll_attributes} style="font-family:'Press Start 2P', monospace;font-size:#{size}px;font-weight:400;line-height:1.35;color:#FBFBF8;text-shadow:6px 6px 0 #14182E">#{h(text.upcase)}</h2>)
  end

  def results_html(question, number, chart)
    placeholder = %(<p style="font-size:36px">Live results appear here when the presenter reaches the poll server.</p>)
    region = if chart == "columns"
      %(<div data-poll="results" data-poll-question="#{number}" data-poll-chart="columns" style="flex:1;display:flex;align-items:flex-end;gap:32px;background:#1B2C8F;color:#FBFBF8;border:6px solid #F2C94C;box-shadow:10px 10px 0 #14182E;padding:32px 40px">)
    else
      %(<div data-poll="results" data-poll-question="#{number}" style="display:flex;flex-direction:column;gap:18px;background:#1B2C8F;color:#FBFBF8;border:6px solid #F2C94C;box-shadow:10px 10px 0 #14182E;padding:32px 40px">)
    end
    [heading_html(question.fetch("prompt"), number, live_prompt: true, chart: chart), region, placeholder, "</div>"].join("\n") + "\n"
  end

  def cards_html(question, number)
    cards = question.fetch("cards").each_with_index.map do |card, index|
      icon = card["icon"] ? %(\n<x-icon name="#{h(card["icon"])}" style="color:#F2C94C;width:88px;height:88px"></x-icon>) : ""
      text = card["text"] ? %(\n<p style="font-size:32px;line-height:1.3;text-align:center">#{h(card["text"])}</p>) : ""
      <<~HTML.chomp
        <div style="flex:1;display:flex;flex-direction:column;align-items:center;gap:20px;background:#1B2C8F;color:#FBFBF8;border:8px solid #F2C94C;box-shadow:12px 12px 0 #14182E;padding:40px">#{icon}
        <h3 style="font-family:'Press Start 2P', monospace;font-size:32px;font-weight:400;line-height:1.3;text-align:center">#{h(card.fetch("title"))}</h3>#{text}
        <p data-poll="count" data-poll-question="#{number}" data-poll-option="#{index + 1}" style="font-family:'Press Start 2P', monospace;font-size:32px;line-height:1.4;color:#F2C94C;text-align:center">0 · 0%</p>
        </div>
      HTML
    end
    heading = heading_html(question["heading"] || question.fetch("prompt"), number, live_prompt: !question["heading"], chart: "cards")
    [heading, %(<div style="flex:1"></div>), %(<div style="display:flex;gap:40px">), *cards, "</div>"].join("\n") + "\n"
  end
end
